#!/usr/bin/env bun

import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import tran from "@1-/tran";
import CODE from "@3-/lang/CODE.js";
import NAME from "@3-/lang/NAME.js";
import read from "@3-/read";
import write from "@3-/write";
import { $ } from "@3-/zx";
import { load } from "js-yaml";

const ROOT = import.meta.dirname,
  I18N_DIR = join(ROOT, "i18n"),
  GEN_RS = join(ROOT, "crate/s0_i18n/src/dict.rs"),
  README_MDT = join(ROOT, "README.mdt"),
  REPO_BLOB = "//github.com/webc-site/sync0/blob/main/i18n/",
  SVG_BASE = "https://cdn.jsdmirror.com/gh/webc-site/svg/i18n/",
  toConstName = (code) => code.replace(/[^a-zA-Z0-9]/g, "_").toUpperCase(),
  cleanStr = (s) =>
    String(s ?? "")
      .replace(/[\u200B-\u200D\uFEFF]/g, "")
      .trim();

const genRs = () => {
  const zh_yml = load(read(join(I18N_DIR, "zh/cli.yml"))) || {},
    en_path = join(I18N_DIR, "en/cli.yml"),
    en_yml = (existsSync(en_path) && load(read(en_path))) || zh_yml,
    key_li = Object.keys(zh_yml);

  const avail_langs = [];
  for (const code of CODE) {
    const p = join(I18N_DIR, code, "cli.yml");
    if (existsSync(p)) {
      avail_langs.push([code, load(read(p)) || {}]);
    }
  }
  for (const dir_name of readdirSync(I18N_DIR, { withFileTypes: true })) {
    if (!dir_name.isDirectory()) continue;
    const code = dir_name.name;
    if (avail_langs.some(([c]) => c === code)) continue;
    const p = join(I18N_DIR, code, "cli.yml");
    if (existsSync(p)) {
      avail_langs.push([code, load(read(p)) || {}]);
    }
  }

  const lines = [
    "// AUTO-GENERATED BY ./tran.js — DO NOT EDIT MANUALLY",
    "",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
    "pub struct I18n {",
    ...key_li.map((k) => `  pub ${k}: &'static str,`),
    "}",
    "",
  ];

  for (const [code, map] of avail_langs) {
    const cname = toConstName(code);
    lines.push(`pub const ${cname}: I18n = I18n {`);
    for (const k of key_li) {
      let val = cleanStr(map[k] ?? en_yml[k] ?? zh_yml[k] ?? "");
      if (code === "en" && k === "err_prefix" && val.toLowerCase() === "mistake") {
        val = "error";
      }
      lines.push(`  ${k}: ${JSON.stringify(val)},`);
    }
    lines.push("};", "");
  }

  lines.push(
    "pub const LANG_CODES: &[&str] = &[",
    ...avail_langs.map(([code]) => `  ${JSON.stringify(code)},`),
    "];",
    "",
    "#[inline]",
    "pub fn by_code(code: &str) -> Option<(&'static str, &'static I18n)> {",
    "  match code {",
  );

  for (const [code] of avail_langs) {
    const cname = toConstName(code),
      lower = code.toLowerCase();
    if (lower !== code) {
      lines.push(
        `    ${JSON.stringify(code)} | ${JSON.stringify(lower)} => Some((${JSON.stringify(code)}, &${cname})),`,
      );
    } else {
      lines.push(`    ${JSON.stringify(code)} => Some((${JSON.stringify(code)}, &${cname})),`);
    }
  }

  lines.push("    _ => None,", "  }", "}", "");
  write(GEN_RS, lines.join("\n"));
};

const genReadmeMdt = () => {
  const link_li = [];
  for (let i = 0; i < CODE.length; ++i) {
    const lang = CODE[i],
      name = NAME[i] || lang;
    if (existsSync(join(I18N_DIR, lang, "README.md"))) {
      link_li.push(
        `<a href="${REPO_BLOB}${lang}/README.md"><img src="${SVG_BASE}${lang}.svg" alt="${name}" /></a>`,
      );
    }
  }
  const mdt = `${link_li.join(" ")}\n\n<+ ./i18n/en/README.md>\n`;
  write(README_MDT, mdt);
};

await tran(ROOT);
genRs();
genReadmeMdt();
await $`bun x mdt .`;
